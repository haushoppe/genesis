#!/usr/bin/env node
// Writes `src/environments/regtest-stack.generated.ts`: the host ports of the
// regtest stack the regtest build talks to, read from the slot environment
// (`E2E_ELECTRS_HOST_PORT`, `E2E_ORD_HOST_PORT`, `E2E_ORD_STOCK_HOST_PORT`,
// `E2E_ORDPOOL_BACKEND_HOST_PORT`) through the SDK's `stackPort`, which falls
// back to slot 0's ports when a variable is unset, exactly as every SDK helper
// does.
//
// A stack runs in a machine-wide slot (`node_modules/ordpool-sdk/scripts/e2e-slots.mjs`)
// and slot N publishes its services at base + 10 N, so the ports are only
// known when the build runs. `environment.regtest.ts` builds its URLs from
// this file, and `src/proxy.conf.regtest.mjs` reads the same file, so the app
// and its dev-server proxy always address one stack.
//
// Runs before every regtest serve (`prestart:regtest`) and before typecheck,
// build and tests, which only need the module to exist. Gitignored: its
// content belongs to one machine and one slot.
import { writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

import e2e from 'ordpool-sdk/e2e';

const out = resolve(dirname(fileURLToPath(import.meta.url)),
  '../src/environments/regtest-stack.generated.ts');

const ports = {
  slot: process.env.E2E_SLOT ?? null,
  electrs: e2e.stackPort('electrs'),
  ord: e2e.stackPort('ord'),
  ordStock: e2e.stackPort('ordStock'),
  ordpoolBackend: e2e.stackPort('ordpoolBackend'),
};

writeFileSync(out, `// AUTO-GENERATED by scripts/write-regtest-stack.mjs from the slot environment. Do not edit.
// The JSON literal below is also parsed by src/proxy.conf.regtest.mjs; keep it on one line.
export const regtestStack = ${JSON.stringify(ports)};
`);
console.log(`[write-regtest-stack] ${JSON.stringify(ports)}`);
